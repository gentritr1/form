const assert=require('node:assert/strict');
const {summarize,range,hashPixels,Timeline}=require('./perf-metrics.cjs');
assert.equal(hashPixels(new Uint8Array([97])),'e40c292c');
const summary=summarize([10,10,20,40],2000,100);
assert.deepEqual(summary,{framesDelivered:4,framesExpected:200,deliveredRatio:.02,windowMs:2000,refreshHz:100,medianMs:10,p95Ms:40,worstMs:40,overBudgetCount:2,overBudgetThresholdMs:15});
assert.equal(summarize([],2000,60).medianMs,null,'An empty bin is not a fast frame.');
assert.equal(summarize([],2000,60).framesExpected,120);
assert.throws(()=>summarize([NaN],2000,60));
assert.deepEqual(range([2,4,3]),{min:2,max:4,samples:3});
assert.equal(range([]),null);
const complete=new Timeline(100,100);
for(let t=110;t<=10100;t+=10)complete.step(t);
assert.deepEqual(complete.actions,[0,1,2,3,4]);
assert.equal(complete.report().reduce((n,s)=>n+s.framesDelivered,0),999);
assert.throws(()=>complete.step(10110));
const stalled=new Timeline(0,60);
stalled.step(16);stalled.step(6500);stalled.step(10000);
assert.equal(stalled.report()[1].framesDelivered,0,'Entire missed windows stay empty.');
assert.equal(stalled.report()[3].worstMs,6484,'Do not trim a stall at a segment boundary.');
const hidden=new Timeline(0,60);hidden.step(16);hidden.step(33,false);
assert.throws(()=>hidden.report(),/hidden/);assert.throws(()=>hidden.step(50));
const backwards=new Timeline(100,60);backwards.step(99);assert.throws(()=>backwards.report(),/timestamp/);
assert.throws(()=>new Timeline(0,60).report(),/Incomplete/);
console.log('Passed: measurement windows, frame reconciliation, long stalls, invalid/hidden runs, summary ranges, pixel hashing.');
